/* Range dans le tampon l'octet recu, s'il y en a un. Ne bloque jamais. */
static void fifo_rx(UART_HandleTypeDef *src, Fifo *f) {
	USART_TypeDef *u = src->Instance;

	if (u->ISR & (USART_ISR_ORE | USART_ISR_FE | USART_ISR_NE)) {
		u->ICR = USART_ICR_ORECF | USART_ICR_FECF | USART_ICR_NECF;
	}

	if (u->ISR & USART_ISR_RXNE_RXFNE) {
		uint8_t c = (uint8_t) u->RDR;
		uint16_t next = (f->head + 1) % FIFO_SIZE;
		if (next != f->tail) {
			f->d[f->head] = c;
			f->head = next;
		}
	}
}

/* Sort du tampon un octet vers l'UART, s'il est libre. Ne bloque jamais. */
static void fifo_tx(UART_HandleTypeDef *dst, Fifo *f) {
	USART_TypeDef *u = dst->Instance;

	if (f->head != f->tail && (u->ISR & USART_ISR_TXE_TXFNF)) {
		u->TDR = f->d[f->tail];
		f->tail = (f->tail + 1) % FIFO_SIZE;
	}
}

/* Lit src, puis envoie vers dst ce que le tampon contient */
static void bridge(UART_HandleTypeDef *src, UART_HandleTypeDef *dst, Fifo *f) {
	fifo_rx(src, f);
	fifo_tx(dst, f);
}
